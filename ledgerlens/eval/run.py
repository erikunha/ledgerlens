@contextmanager
def _langsmith_env(settings: Any) -> Iterator[None]:
    """Turns LangSmith tracing on with the key from the settings, which is not in `os.environ`.

    Traces of the graph and of the models inside the target only reach the experiment if the environment has the key.
    The environment goes back to what it was on exit. The key is never printed.
    """
    changes = {
        "LANGSMITH_API_KEY": settings.langsmith_api_key.get_secret_value(),
        "LANGSMITH_TRACING": "true",
        "LANGSMITH_PROJECT": settings.langsmith_project or "ledgerlens",
    }
    saved = {name: os.environ.get(name) for name in changes}
    try:
        os.environ.update(changes)
        yield
    finally:
        for name, value in saved.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value


@contextmanager
def _tracing_unless(enabled: bool) -> Iterator[None]:
    """Turns LangSmith tracing off inside the block when `enabled` is false."""
    if enabled:
        yield
        return
    from langsmith import tracing_context

    with tracing_context(enabled=False):
        yield


def _idle_client() -> Any:
    """LangSmith client with no batch sending, for `evaluate` with no storage.

    Without a client, `evaluate` creates the global one, whose background thread queries the API (`/info`) and sends
    traces with the emptied key, which LangSmith refuses with 401.
    """
    from langsmith import Client

    return Client(auto_batch_tracing=False)


def _untraced(evaluator: Callable[..., Any]) -> Callable[..., Any]:
    """The evaluator with no trace: `evaluate` turns "local" mode back on around each evaluator, and the LLM judge
    then opens traces the client would send. Inside this wrapper nothing is opened."""
    from langsmith import tracing_context

    @wraps(evaluator)
    def run(*args: Any, **kwargs: Any) -> Any:
        with tracing_context(enabled=False):
            return evaluator(*args, **kwargs)

    return run


def _price(model: str, usage: dict[str, int]) -> float | None:
    """Cost in dollars at list price; `None` if the model is not in the table."""
    name = model.split(":", 1)[-1]
    prices = next((p for key, p in PRICE_PER_MTOK.items() if name.startswith(key)), None)
    if prices is None:
        return None
    return round((usage["input_tokens"] * prices[0] + usage["output_tokens"] * prices[1]) / 1_000_000, 6)


def _sum_usage(by_model: dict[str, dict[str, Any]], default_model: str) -> dict[str, Any]:
    """Adds up the tokens of every model used. Input and output come from LangChain's `usage_metadata`."""
    total = {"input_tokens": 0, "output_tokens": 0, "total_tokens": 0}
    cost: float | None = 0.0
    for name, usage in by_model.items():
        for key in total:
            total[key] += int(usage.get(key, 0))
        model_cost = _price(name or default_model, {k: int(usage.get(k, 0)) for k in total})
        cost = None if model_cost is None or cost is None else cost + model_cost
    return {**total, "cost_usd": None if cost is None else round(cost, 6)}


def _ensure_dataset(client: Any, cases: Sequence[EvalCase]) -> None:
    """Creates the dataset with the cases if it does not exist yet. The example ids are the same as in offline mode."""
    if client.has_dataset(dataset_name=DATASET_NAME):
        # The dataset already exists: each example's reference outputs are updated to today's cases.
        dataset = client.read_dataset(dataset_name=DATASET_NAME)
        client.update_examples(
            dataset_id=dataset.id,
            updates=[{"id": e.id, "inputs": e.inputs, "outputs": e.outputs} for e in map(_example, cases)],
        )
        return
    dataset = client.create_dataset(DATASET_NAME, description="LedgerLens evaluation cases")
    examples = [_example(c) for c in cases]
    client.create_examples(
        dataset_id=dataset.id,
        ids=[e.id for e in examples],
        inputs=[e.inputs for e in examples],
        outputs=[e.outputs for e in examples],
    )


def _ensure_verification(client: Any) -> list[Any]:
    """Creates the verification set dataset if it does not exist and returns its examples."""
    cases = load_verification_cases()
    if not client.has_dataset(dataset_name=VERIFICATION_DATASET):
        dataset = client.create_dataset(VERIFICATION_DATASET, description="Verifier validation cases")
        examples = [_verification_example(c) for c in cases]
        client.create_examples(
            dataset_id=dataset.id,
            ids=[e.id for e in examples],
            inputs=[e.inputs for e in examples],
            outputs=[e.outputs for e in examples],
        )
    return list(client.list_examples(dataset_name=VERIFICATION_DATASET))


def refusal_reason(exc: Exception) -> str:
    """The reason for a refusal on one line: the HTTP code and the API message, with no address or identifier."""
    text = " ".join(str(exc).split())
    status = re.search(r"\b(4\d\d|5\d\d)\b", text)
    message = re.search(r'"error":\s*"([^"]+)"', text)
    if message:
        return (f"HTTP {status.group(1)}: " if status else "") + message.group(1)
    return re.sub(r"https?://\S+|[0-9a-f]{8}-[0-9a-f-]{27,}", "", text)[:200] or type(exc).__name__


def ingestion_refusal(settings: Any) -> str | None:
    """Asks LangSmith once whether it accepts traces. Returns the refusal reason, or `None` if it accepts.

    Uses a client with no batch sending, which posts the run right away and raises the API error (the monthly trace
    quota, for example); with batch sending the error would only show in the log, after the model spend.
    """
    import datetime as dt

    from langsmith import Client

    probe = Client(api_key=settings.langsmith_api_key.get_secret_value(), auto_batch_tracing=False)
    try:
        probe.create_run(
            name="ledgerlens-ingestion-probe",
            inputs={},
            run_type="chain",
            start_time=dt.datetime.now(dt.UTC),
            project_name=settings.langsmith_project or "ledgerlens",
        )
    except Exception as exc:  # any refusal counts: the reason goes into the report
        return refusal_reason(exc)
    return None


def run_online(
    cases: Sequence[EvalCase],
    *,
    variants: Sequence[str] = VARIANTS,
    settings: Any = None,
    client: Any = None,
    evaluate_fn: Callable[..., Any] | None = None,
    work_dir: Path | None = None,
    model: BaseChatModel | None = None,
    dataset_cases: Sequence[EvalCase] | None = None,
    repeats: int = 1,
    refusal: Callable[[Any], str | None] | None = None,
) -> dict[str, Any]:
    """Uploads the set as a dataset and creates one experiment per variant, with the configured model.

    Returns the report (`online` mode) plus `experiments`: the name and address of each experiment. The
    addresses stay out of the written report. `dataset_cases` are the dataset's cases when `cases` is a
    slice. `repeats` runs each variant N times, each in its own experiment, and the report carries the mean,
    minimum and maximum (`aggregate_runs`). `refusal` decides whether LangSmith accepts traces (`ingestion_refusal`);
    if it refuses, nothing is sent: the runs use the real model, FX and NLI, with tracing
    turned off, and the report says they were not stored and why.
    `client`, `evaluate_fn`, `work_dir` and `model` exist so the tests can swap the network and the model for doubles.
    """
    from langchain_core.callbacks import get_usage_metadata_callback
    from langsmith import Client
    from langsmith import evaluate as langsmith_evaluate

    settings = settings or get_settings()
    evaluate_fn = evaluate_fn or langsmith_evaluate
    by_id = {c.id: c for c in cases}
    judge_model = model or get_chat_model(settings, temperature=0)
    refused = (refusal or ingestion_refusal)(settings)
    environment = _langsmith_env(settings) if refused is None else _no_tracing()
    with tempfile.TemporaryDirectory(prefix="ledgerlens_eval_") as scratch, environment:
        root = work_dir or Path(scratch)
        if refused is None:
            client = client or Client(api_key=settings.langsmith_api_key.get_secret_value())
            _ensure_dataset(client, dataset_cases or cases)
        wanted = set(by_id)
        # The remote examples carry the dataset id, which `evaluate` requires; the reference (outputs) comes from the
        # local cases, because the remote dataset may have fallen behind.
        local = {c.id: _example(c) for c in dataset_cases or cases}
        examples = []
        for remote in client.list_examples(dataset_name=DATASET_NAME) if refused is None else []:
            if remote.inputs["case_id"] in wanted:
                outputs = local[remote.inputs["case_id"]].outputs
                if hasattr(remote, "model_copy"):  # LangSmith's `Example` is immutable
                    examples.append(remote.model_copy(update={"outputs": outputs}))
                else:
                    example = copy.copy(remote)
                    example.outputs = outputs
                    examples.append(example)
        if refused is not None:
            examples = [local[c.id] for c in cases]
        # Ledger from the versioned sample: the cases' expected facts come from it. The index is the configured one.
        world = World(
            root,
            build_sample_ledger(root / "ledger.db"),
            settings.index_dir,
            get_embeddings(settings),
            get_nli(False, require_real=True),
            offline=False,
        )
        judge = explanation_judge(judge_model)
        evaluators = [*offline_evaluators(), judge if refused is None else _untraced(judge)]
        run_rows: list[list[dict]] = []
        run_usage: list[dict[str, Any]] = []
        experiments: dict[str, Any] = {}
        for _ in range(repeats):
            rows: list[dict] = []
            usage: dict[str, Any] = {}
            names: dict[str, str] = {}
            for variant in variants:

                def target(inputs: dict[str, Any], variant: str = variant) -> dict[str, Any]:
                    # With no storage, the graphs open no trace: `evaluate`'s "local" mode does not prevent them
                    # and the client would send them with the emptied key (401).
                    with _tracing_unless(refused is None):
                        return RUNNERS[variant](by_id[inputs["case_id"]], world, model)

                storage: dict[str, Any] = (
                    {"client": client} if refused is None else {"upload_results": False, "client": _idle_client()}
                )
                with get_usage_metadata_callback() as counter, _tracing_unless(refused is None):
                    results = evaluate_fn(
                        target,
                        data=examples,
                        evaluators=evaluators,
                        max_concurrency=0,
                        **storage,
                        experiment_prefix=f"ledgerlens-{variant}",
                        metadata={"variant": variant, "model": settings.model, "project": settings.langsmith_project},
                    )
                    rows += _rows(list(results), variant, by_id, ONLINE_METRICS)
                usage[variant] = _sum_usage(dict(counter.usage_metadata), settings.model or "")
                stored = refused is None
                names[variant] = results.experiment_name if stored else None
                experiment = {
                    "name": results.experiment_name if stored else None,
                    "url": getattr(results, "url", None) if stored else None,
                }
                if repeats == 1:
                    experiments[variant] = experiment
                else:
                    experiments.setdefault(variant, []).append(experiment)
            run_rows.append(rows)
            run_usage.append({"usage": usage, "names": names})
        if refused is None:
            verification = evaluate_verification(
                world.nli,
                examples=_ensure_verification(client),
                client=client,
                evaluate_fn=evaluate_fn,
                upload=True,
            )
        else:
            verification = evaluate_verification(world.nli, evaluate_fn=evaluate_fn)
        experiments["verification"] = {"name": verification["experiment"], "url": verification["_url"]}
    reports = []
    for rows, extra in zip(run_rows, run_usage, strict=True):
        usage = extra["usage"]
        part = build_report(rows, cases, "online", metrics_keys=ONLINE_METRICS, variants_run=variants)
        for variant in variants:
            part["variants"][variant]["usage"] = usage[variant]
            part["variants"][variant]["experiment"] = extra["names"][variant]
        totals = {k: sum(usage[v][k] for v in variants) for k in ("input_tokens", "output_tokens", "total_tokens")}
        costs = [usage[v]["cost_usd"] for v in variants]
        part["usage"] = {**totals, "cost_usd": None if None in costs else round(sum(costs), 6)}
        reports.append(part)
    report = aggregate_runs(reports)
    report["verification"] = _public_verification(verification)
    report["model"] = settings.model
    report["nli"] = nli_name(world.nli)
    report["note"] = online_note(world.nli)
    if repeats > 1:
        report["note"] = report["note"].replace(
            "One run per case", f"{repeats} runs per case and per variant, each in its own experiment"
        )
    report["experiments"] = experiments
    report["storage"] = {"stored": refused is None, "reason": refused}
    return report


def _public(report: dict[str, Any]) -> dict[str, Any]:
    """The report without the experiment addresses, which stay in the local note."""
    return {k: v for k, v in report.items() if k != "experiments"}


def previous_stored_experiments(path: Path) -> dict[str, Any] | None:
    """Names of the experiments the report already written at `path` keeps in LangSmith, or `None` if there are none.

    A report that already came from an unstored run passes on the names it carried itself.
    """
    if not path.exists():
        return None
    old = json.loads(path.read_text(encoding="utf-8"))
    if old.get("previous_stored"):
        return old["previous_stored"]
    names = {k: v["experiment"] for k, v in old.get("variants", {}).items() if v.get("experiment")}
    verification = (old.get("verification") or {}).get("experiment")
    return {"variants": names, "verification": verification} if names else None


def attach_verification(out_dir: Path, verification: dict[str, Any]) -> dict[str, Any]:
    """Adds the verification experiment to the online report already written and writes the JSON and Markdown again."""
    report = json.loads((out_dir / "report_online.json").read_text(encoding="utf-8"))
    report["verification"] = _public_verification(verification)
    write_report(report, out_dir)
    return report


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Evaluates the three LedgerLens variants.")
    parser.add_argument(
        "--online", action="store_true", help="creates experiments in LangSmith (requires LANGSMITH_API_KEY)"
    )
    parser.add_argument("--out", type=Path, default=OUT_DIR, help="folder for the reports")
    parser.add_argument("--variants", default="A,B,C", help="online only: variants to run, separated by commas")
    parser.add_argument(
        "--verification-only",
        action="store_true",
        help="online only: uploads only the verification set experiment and adds it to the written online report",
    )
    parser.add_argument(
        "--repeats", type=int, default=1, help="online only: runs each variant N times, each in its own experiment"
    )
    parser.add_argument("--limit", type=int, default=None, help="online only: runs only the first N cases")
    args = parser.parse_args(argv)
    if args.repeats < 1:
        print("--repeats takes an integer greater than or equal to 1.", file=sys.stderr)
        return 2
    if args.online:
        settings = get_settings()
        if settings.langsmith_api_key is None or settings.offline:
            print("--online requires LANGSMITH_API_KEY and a non-offline mode (LEDGERLENS_OFFLINE=0).", file=sys.stderr)
            return 2
        if args.verification_only:
            from langsmith import Client

            with _langsmith_env(settings):
                client = Client(api_key=settings.langsmith_api_key.get_secret_value())
                result = evaluate_verification(
                    get_nli(False, require_real=True), examples=_ensure_verification(client), client=client, upload=True
                )
            attach_verification(args.out, result)
            print("verification", _public_verification(result))
            print("verification experiment", result["experiment"], result["_url"])
            return 0
        variants = tuple(v.strip().upper() for v in args.variants.split(",") if v.strip())
        if not variants or any(v not in VARIANTS for v in variants):
            print(f"--variants takes {', '.join(VARIANTS)}.", file=sys.stderr)
            return 2
        everything = load_cases()
        cases = everything[: args.limit]
        report = run_online(cases, variants=variants, settings=settings, dataset_cases=everything, repeats=args.repeats)
        full = len(cases) == len(everything) and variants == VARIANTS
        if full:
            if not report["storage"]["stored"]:
                previous = previous_stored_experiments(args.out / "report_online.json")
                if previous:
                    report["previous_stored"] = previous
            write_report(_public(report), args.out)
        for key, data in report["variants"].items():
            print(key, data["label"], data.get("aggregate", data["metrics"]), data["usage"])
        print("verification", report["verification"])
        print("total", report["usage"])
        for key, experiment in report["experiments"].items():
            for item in experiment if isinstance(experiment, list) else [experiment]:
                print("experiment", key, item["name"] or "not stored", item["url"])
        if not report["storage"]["stored"]:
            print("LangSmith refused the upload:", report["storage"]["reason"])
        if not full:
            print("partial run: no report written.")
        return 0
    with tempfile.TemporaryDirectory(prefix="ledgerlens_eval_") as work:
        cases = build_cases(build_sample_ledger(Path(work) / "cases.db"))
        report = run_offline(cases, Path(work) / "world")
    write_report(report, args.out)
    for key, data in report["variants"].items():
        print(key, data["label"], {m: data["metrics"][m] for m in METRICS})
    return 0


if __name__ == "__main__":
    sys.exit(main())
