"""Evaluation run: three variants over the cases, with an offline report or experiments in LangSmith.

Why it exists: to say what each layer brings, the same set of cases goes through three variants:

- **A**, chain with no tools: prompt, model and text parser. It answers only from what the model knows.
- **B**, ReAct agent (`legacy_react`): the four investigation tools, with no verification of its own.
- **C**, full agent (`integrator`): the six tools, the verifier and the case memory.

The evaluators (`evaluators.py`) score all three the same way. The claims of A and B go through the same
verifier after the answer, so groundedness is comparable. `requires_human_review` and
`recommended_action` are read from the verifier's result, never recomputed here.

**Offline** (default): each variant runs with scripted models, which replay each case's script
(`dataset.py`). The ledger comes from the versioned sample in a temporary folder, the policies use deterministic
embeddings and the NLI is the stand-in. Nothing uses the network or a key. The result measures the plumbing (trace
conversion, evaluators, report), not the quality of a model. The run goes through `langsmith.evaluate`
with `upload_results=False` and `Example` objects, the same format as the online experiment.

**Online** (`--online`): requires `LANGSMITH_API_KEY` and a non-offline mode. It uploads the set as a dataset, runs
the variants with the configured model (temperature 0) and the real tools (FX over the network, SQL generated by the
model, policy index) and creates one experiment per variant. The ledger is the versioned sample, the same one the
cases' expected facts come from. The verifier is the real one, but with the NLI stand-in when `transformers` is not
installed. Besides the six code evaluators, the LLM judge scores the explanation. Tokens and cost
come from the model, per variant. A full run writes `report_online.json` and `report_online.md`; with
`--variants` or `--limit` it only prints the summary, to test the plumbing and the cost first.

Usage: `uv run python -m ledgerlens.eval.run [--online [--variants A,B,C] [--limit N]] [--out FOLDER]`.
"""

