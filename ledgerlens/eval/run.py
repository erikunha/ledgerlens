def _example(case: EvalCase):
    from langsmith.schemas import Example

    return Example(
        id=uuid5(NAMESPACE_URL, f"ledgerlens-eval/{case.id}"),
        inputs={"case_id": case.id, "question": case.question},
        outputs={
            "facts": case.expected_facts,
            "trajectory": reference_messages(case.expected_tools),
            "equivalent_tools": case.equivalent_tools,
        },
    )


def _rows(results: Any, variant: str, by_id: dict[str, EvalCase], metrics: Sequence[str]) -> list[dict]:
    """One row per case from the `evaluate` rows. A case that failed or has no score gets 0 and the error."""
    out = []
    for row in results:
        case = by_id[row["example"].inputs["case_id"]]
        evaluations = row["evaluation_results"]["results"]
        scores = {r.key: r.score for r in evaluations}
        comments = {r.key: r.comment for r in evaluations}
        run = row["run"]
        outputs = run.outputs or {}
        entry = {
            "case": case.id,
            "variant": variant,
            "kind": case.kind,
            "scenario": case.scenario,
            "scores": {key: round(float(scores.get(key) or 0.0), 4) for key in metrics},
            "missing_facts": comments.get("correctness") if (scores.get("correctness") or 0.0) < 1.0 else None,
            "tools": outputs.get("tools", []),
            "expected_tools": case.expected_tools,
            "requires_human_review": outputs.get("requires_human_review"),
            "recommended_action": outputs.get("recommended_action"),
            "plan_deviations": outputs.get("plan_deviations", []),
            "answer": outputs.get("answer", ""),
        }
        if getattr(run, "error", None):
            entry["error"] = str(run.error).splitlines()[0][:200]  # first line only: it may cite the environment
        out.append(entry)
    return sorted(out, key=lambda r: r["case"])


def evaluate_variant(
    variant: str, cases: Sequence[EvalCase], world: World, evaluators: Sequence[Evaluator]
) -> list[dict]:
    """Runs a variant through `langsmith.evaluate` without sending anything and returns one row per case."""
    from langsmith import evaluate, tracing_context

    by_id = {c.id: c for c in cases}

    def target(inputs: dict[str, Any]) -> dict[str, Any]:
        # The integrator's graph opens its own traces; inside the target they are off.
        with tracing_context(enabled=False):
            return RUNNERS[variant](by_id[inputs["case_id"]], world)

    # `enabled=False` prevents sending traces even if the environment has a key and tracing turned on.
    with warnings.catch_warnings(), tracing_context(enabled=False):
        warnings.simplefilter("ignore")  # `upload_results` is still beta
        results = evaluate(
            target,
            data=[_example(c) for c in cases],
            evaluators=list(evaluators),
            upload_results=False,
            max_concurrency=0,
            experiment_prefix=f"ledgerlens-{variant}",
        )
        rows = list(results)
    return _rows(rows, variant, by_id, METRICS)


def _verification_example(case: dict[str, Any]):
    from langsmith.schemas import Example

    return Example(
        id=uuid5(NAMESPACE_URL, f"ledgerlens-verification/{case['id']}"),
        inputs={"case_id": case["id"], "type": case["type"]},
        outputs={"verdict": expected_verdict(case)},
    )


def predict_verdict(case: dict[str, Any], nli: Nli) -> str:
    """The verifier's verdict for the case: the claim's label, or the coherence one in the coherence cases."""
    out = verify_result(verification_result(case), nli=nli)
    if case["type"] == "coherence":
        return "supported" if out.coherence.passed else "contradicted"
    return out.verdicts[0].label


def _summary_evaluators() -> list[Callable[..., dict[str, Any]]]:
    """The summaries LangSmith keeps in the experiment: the same math as `verification_summary`."""

    def pairs(runs: Sequence[Any], examples: Sequence[Any]) -> list[tuple[str | None, str]]:
        return [((r.outputs or {}).get("verdict"), e.outputs["verdict"]) for r, e in zip(runs, examples, strict=True)]

    def recall(runs: Sequence[Any], examples: Sequence[Any]) -> dict[str, Any]:
        return {
            "key": "contradiction_recall",
            "score": verification_summary(pairs(runs, examples))["contradiction_recall"],
        }

    def false_positive(runs: Sequence[Any], examples: Sequence[Any]) -> dict[str, Any]:
        return {
            "key": "false_positive_rate",
            "score": verification_summary(pairs(runs, examples))["false_positive_rate"],
        }

    return [recall, false_positive]


def evaluate_verification(
    nli: Nli,
    *,
    examples: Sequence[Any] | None = None,
    client: Any = None,
    evaluate_fn: Callable[..., Any] | None = None,
    upload: bool = False,
) -> dict[str, Any]:
    """Runs the verifier over `verification_set.jsonl` as an experiment and returns the metrics.

    Offline (`upload=False`) `evaluate` sends nothing; online it uploads the experiment, with the verdict per case
    and, as a summary, the contradiction recall and the false positive rate.
    """
    from langsmith import evaluate as langsmith_evaluate

    cases = {c["id"]: c for c in load_verification_cases()}
    data = list(examples) if examples is not None else [_verification_example(c) for c in cases.values()]

    def target(inputs: dict[str, Any]) -> dict[str, Any]:
        return {"verdict": predict_verdict(cases[inputs["case_id"]], nli)}

    kwargs: dict[str, Any] = {"upload_results": False, "client": _idle_client()} if not upload else {"client": client}
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        if upload:
            results = (evaluate_fn or langsmith_evaluate)(
                target,
                data=data,
                evaluators=[verdict_match],
                summary_evaluators=_summary_evaluators(),
                max_concurrency=0,
                experiment_prefix="ledgerlens-verification",
                metadata={"nli": nli_name(nli)},
                **kwargs,
            )
        else:
            from langsmith import tracing_context

            with tracing_context(enabled=False):
                results = (evaluate_fn or langsmith_evaluate)(
                    target,
                    data=data,
                    evaluators=[verdict_match],
                    summary_evaluators=_summary_evaluators(),
                    max_concurrency=0,
                    experiment_prefix="ledgerlens-verification",
                    **kwargs,
                )
        rows = list(results)
    pairs = [((r["run"].outputs or {}).get("verdict"), r["example"].outputs["verdict"]) for r in rows]
    summary = verification_summary(pairs)
    summary["misses"] = sorted(
        r["example"].inputs["case_id"]
        for r, (predicted, expected) in zip(rows, pairs, strict=True)
        if predicted != expected
    )
    summary["nli"] = nli_name(nli)
    summary["experiment"] = getattr(results, "experiment_name", None) if upload else None
    summary["_url"] = getattr(results, "url", None) if upload else None
    return summary


def build_report(
    rows: list[dict],
    cases: Sequence[EvalCase],
    mode: str,
    *,
    metrics_keys: Sequence[str] = METRICS,
    variants_run: Sequence[str] = VARIANTS,
) -> dict[str, Any]:
    variants: dict[str, Any] = {}
    for variant in variants_run:
        mine = [r for r in rows if r["variant"] == variant]
        metrics = {m: round(sum(r["scores"][m] for r in mine) / len(mine), 4) for m in metrics_keys}
        failed = {m: [r["case"] for r in mine if r["scores"][m] < 1.0] for m in metrics_keys}
        variants[variant] = {
            "label": LABELS[variant],
            "metrics": metrics,
            "human_review": sum(bool(r["requires_human_review"]) for r in mine),
            "failed_cases": failed,
        }
    goal: dict[str, Any] = {}
    if "A" in variants and "C" in variants:
        a, c = variants["A"]["metrics"], variants["C"]["metrics"]
        goal = {
            "c_beats_a_in_correctness": c["correctness"] > a["correctness"],
            "c_trajectory_unordered": c["trajectory_unordered_match"],
            "c_trajectory_at_least_80_percent": c["trajectory_unordered_match"] >= GOAL_TRAJECTORY_MIN,
            "c_trajectory_equivalent_unordered": c["trajectory_equivalent_unordered_match"],
            "c_trajectory_equivalent_at_least_80_percent": c["trajectory_equivalent_unordered_match"]
            >= GOAL_TRAJECTORY_MIN,
        }
    return {
        "mode": mode,
        "note": NOTE if mode == "offline" else online_note(StubNli()),
        "cases": len(cases),
        "variants": variants,
        "goal": goal,
        "expectation_changes": [change.model_dump() for change in EXPECTATION_CHANGES],
        "per_case": sorted(rows, key=lambda r: (r["variant"], r["case"])),
    }


def _spread(values: Sequence[float]) -> dict[str, float]:
    return {"mean": round(sum(values) / len(values), 4), "min": min(values), "max": max(values)}


def aggregate_runs(reports: Sequence[dict[str, Any]]) -> dict[str, Any]:
    """Joins the reports of repeated runs: mean, minimum and maximum per variant and metric.

    A single run returns its own report. With several, `metrics` becomes the mean, `aggregate` keeps
    mean, minimum and maximum, `runs` keeps each run's experiment and scores, and `failed_cases` lists the
    cases that scored below the maximum in at least one run.
    """
    if len(reports) == 1:
        return reports[0]
    first = reports[0]
    variants: dict[str, Any] = {}
    for key, data in first["variants"].items():
        mine = [r["variants"][key] for r in reports]
        aggregate = {m: _spread([v["metrics"][m] for v in mine]) for m in data["metrics"]}
        reviews = _spread([v["human_review"] for v in mine])
        variants[key] = {
            "label": data["label"],
            "metrics": {m: spread["mean"] for m, spread in aggregate.items()},
            "aggregate": aggregate,
            "human_review": reviews["mean"],
            "human_review_aggregate": reviews,
            "runs": [
                {"experiment": v.get("experiment"), "metrics": v["metrics"], "human_review": v["human_review"]}
                for v in mine
            ],
            "failed_cases": {m: sorted({c for v in mine for c in v["failed_cases"][m]}) for m in data["failed_cases"]},
        }
        if "usage" in data:
            usage = {k: sum(v["usage"][k] for v in mine) for k in ("input_tokens", "output_tokens", "total_tokens")}
            costs = [v["usage"]["cost_usd"] for v in mine]
            variants[key]["usage"] = {**usage, "cost_usd": None if None in costs else round(sum(costs), 6)}
    goal: dict[str, Any] = {}
    if "A" in variants and "C" in variants:
        a, c = variants["A"]["metrics"], variants["C"]["metrics"]
        goal = {
            "c_beats_a_in_correctness": c["correctness"] > a["correctness"],
            "c_trajectory_unordered": c["trajectory_unordered_match"],
            "c_trajectory_at_least_80_percent": c["trajectory_unordered_match"] >= GOAL_TRAJECTORY_MIN,
            "c_trajectory_equivalent_unordered": c["trajectory_equivalent_unordered_match"],
            "c_trajectory_equivalent_at_least_80_percent": c["trajectory_equivalent_unordered_match"]
            >= GOAL_TRAJECTORY_MIN,
        }
    merged = {**first, "repeats": len(reports), "variants": variants, "goal": goal}
    merged["per_case"] = sorted(
        ({**row, "run": index} for index, report in enumerate(reports, start=1) for row in report["per_case"]),
        key=lambda r: (r["variant"], r["run"], r["case"]),
    )
    if all("usage" in r for r in reports):
        costs = [r["usage"]["cost_usd"] for r in reports]
        merged["usage"] = {
            **{k: sum(r["usage"][k] for r in reports) for k in ("input_tokens", "output_tokens", "total_tokens")},
            "cost_usd": None if None in costs else round(sum(costs), 6),
        }
    return merged


@contextmanager
def _no_tracing() -> Iterator[None]:
    """Turns tracing off and empties the LangSmith keys: the offline run sends nothing, even with the
    environment set up for it. The environment goes back to what it was on exit."""
    # An empty key, not a missing one: a missing variable would be filled in by whoever loads the `.env`.
    changes = {
        "LANGSMITH_TRACING": "false",
        "LANGCHAIN_TRACING_V2": "false",
        "LANGSMITH_API_KEY": "",
        "LANGCHAIN_API_KEY": "",
    }
    saved = {name: os.environ.get(name) for name in changes}
    try:
        for name, value in changes.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value
        yield
    finally:
        for name, value in saved.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value


def _public_verification(verification: dict[str, Any]) -> dict[str, Any]:
    """The verification experiment's metrics without the address, which stays in the local note."""
    return {k: v for k, v in verification.items() if k != "_url"}


def run_offline(cases: Sequence[EvalCase], work_dir: Path) -> dict[str, Any]:
    """Runs the three variants offline over `cases` and returns the report. `work_dir` keeps the ledger and index."""
    with _no_tracing():
        world = build_offline_world(work_dir)
        rows: list[dict] = []
        for variant in VARIANTS:
            rows += evaluate_variant(variant, cases, world, offline_evaluators())
        verification = evaluate_verification(world.nli)
    report = build_report(rows, cases, "offline")
    report["verification"] = _public_verification(verification)
    return report


def _nli_bullets(report: dict[str, Any]) -> list[str]:
    nli = report.get("nli", "stub")
