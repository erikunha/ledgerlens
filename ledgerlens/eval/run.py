class _HashingModel:
    """Stands in for the fastembed model: each word adds 1 at a fixed position out of 64. Deterministic."""

    def __init__(self, model_name: str, **kwargs: object) -> None:
        self.model_name = model_name

    @staticmethod
    def _vector(text: str) -> np.ndarray:
        vector = np.zeros(64, dtype=np.float32)
        for word in re.findall(r"\w+", text.lower()):
            vector[zlib.crc32(word.encode()) % 64] += 1.0
        return vector

    def passage_embed(self, texts: Sequence[str], **kwargs: object):
        return (self._vector(t) for t in texts)

    def query_embed(self, query: str | Sequence[str], **kwargs: object):
        return (self._vector(t) for t in ([query] if isinstance(query, str) else query))


class OfflineEmbeddings(FastEmbedEmbeddings):
    """Embeddings with no download: the same fastembed wrapper over a word-count model."""

    def __init__(self) -> None:
        super().__init__("offline-wordcount")

    def _load(self) -> Any:
        if self._model is None:
            self._model = _HashingModel(self.model_name)
        return self._model


@dataclass
class World:
    """What the three variants share: the ledger, the policy index and a folder for the memories."""

    root: Path
    db_path: Path
    index_root: Path
    embeddings: FastEmbedEmbeddings
    nli: Nli
    offline: bool = True

    def case_memory(self, case: EvalCase, variant: str) -> CaseMemory:
        """A new case memory per run, so a saved case does not change the next one."""
        return CaseMemory(self.root / "memory" / variant / case.id, embeddings=self.embeddings)


def build_offline_world(root: Path) -> World:
    root.mkdir(parents=True, exist_ok=True)
    embeddings = OfflineEmbeddings()
    index_root = root / "index"
    build_policy_index(load_policy_documents(), embeddings, index_dir_for(index_root, embeddings))
    return World(root, build_sample_ledger(root / "ledger.db"), index_root, embeddings, StubNli())


# --- the three variants -----------------------------------------------------------------------------


def _online_model() -> BaseChatModel:
    """The configured model with temperature 0, so the run is as repeatable as possible."""
    return get_chat_model(temperature=0)


def _tool_kwargs(case: EvalCase, world: World, steps: Sequence[Any]) -> dict[str, Any]:
    sqls = [s.sql for s in steps if s.tool == "query_ledger" and s.sql]
    if world.offline:
        query_model = ScriptedChatModel(script=sqls) if sqls else None
    else:
        query_model = _online_model()  # the `query_ledger` SQL generator also runs at temperature 0
    return {
        "query_model": query_model,
        "db_path": world.db_path,
        "fx_client": FxClient(mode="fixtures" if world.offline else "live", fault=case.fx_fault, sleep=lambda _: None),
        "index_root": world.index_root,
        "embeddings": world.embeddings,
    }


def _bare_result(case: EvalCase, answer: str, variant: str) -> InvestigationResult:
    return InvestigationResult(
        session_id=f"eval-{variant}-{case.id}",
        question=case.question,
        answer=answer,
        claims=[],
        evidence=[],
        verdicts=[],
        coherence=Coherence(passed=True),
        recommended_action="none",
        requires_human_review=False,
    )


def _outputs(result: InvestigationResult) -> dict[str, Any]:
    return {
        "answer": result.answer,
        "trajectory": trace_to_messages(result.tool_trace),
        "tools": [r.tool for r in result.tool_trace],
        "verdicts": [v.label for v in result.verdicts],
        "requires_human_review": result.requires_human_review,
        "recommended_action": result.recommended_action,
        "plan_deviations": result.plan_deviations,
    }


def run_variant_a(case: EvalCase, world: World, model: BaseChatModel | None = None) -> dict[str, Any]:
    model = model or (ScriptedChatModel(script=[A_ANSWER]) if world.offline else _online_model())
    chain = (
        ChatPromptTemplate.from_messages([("system", A_SYSTEM), ("human", "{question}")]) | model | StrOutputParser()
    )
    answer = chain.invoke({"question": case.question})
    return _outputs(verify_result(_bare_result(case, answer, "A"), nli=world.nli, ledger_db=world.db_path))


def _b_answer(case: EvalCase) -> str:
    """B's scripted answer: only the sentences whose evidence its tools produce."""
    available = {EVIDENCE_PREFIX[s.tool] for s in case.steps if s.tool in B_TOOLS}
    kept = [line for line in case.lines if all(e.split(":", 1)[0] in available for e in line.evidence)]
    if not kept:
        return B_NO_DATA
    return case.model_copy(update={"lines": kept}).answer


def _react_script(steps: Sequence[Any], answer: str) -> list[str]:
    turns = [
        f"Thought: I need to use {s.tool}.\nAction: {s.tool}\nAction Input: {json.dumps(s.args, ensure_ascii=False)}"
        for s in steps
    ]
    return [*turns, f"Thought: I now know the final answer\nFinal Answer: {answer}"]


def _react_messages(question: str, steps: Sequence[Any], output: str) -> list[BaseMessage]:
    """The ReAct steps as messages, so the same result builder as the integrator serves both."""
    messages: list[BaseMessage] = [HumanMessage(question)]
    for index, (action, observation) in enumerate(steps, start=1):
        if action.tool == "_Exception":  # a malformed ReAct step, retried by the agent: not a tool call
            continue
        try:
            args = json.loads(action.tool_input) if isinstance(action.tool_input, str) else dict(action.tool_input)
        except ValueError:
            args = {"input": str(action.tool_input)}
        call = {
            "name": action.tool,
            "args": args if isinstance(args, dict) else {"input": args},
            "id": f"react-{index}",
            "type": "tool_call",
        }
        messages.append(AIMessage(content="", tool_calls=[call]))
        messages.append(ToolMessage(content=str(observation), tool_call_id=call["id"], name=action.tool))
    messages.append(AIMessage(content=output))
    return messages


def run_variant_b(case: EvalCase, world: World, model: BaseChatModel | None = None) -> dict[str, Any]:
    steps = [s for s in case.steps if s.tool in B_TOOLS]
    kwargs = _tool_kwargs(case, world, steps)
    model = model or (
        ScriptedChatModel(script=_react_script(steps, _b_answer(case))) if world.offline else _online_model()
    )
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # the legacy agent warns that it is deprecated
        agent = build_legacy_agent(model, build_legacy_tools(**kwargs))
        out = agent.invoke({"input": case.question})
    messages = _react_messages(case.question, out["intermediate_steps"], out["output"])
    result = _assemble(case.question, f"eval-B-{case.id}", messages, [0] * len(out["intermediate_steps"]))
    return _outputs(verify_result(result, nli=world.nli, ledger_db=world.db_path))


def _scripted_triage(case: EvalCase) -> ScriptedChatModel:
    """The case's offline triage: one step per script call and a last one with no tool, which writes the answer."""
    tools = [s.tool for s in case.steps]
    plan = [
        PlanStep(id=f"S{n}", goal=f"use {tool}", tool=tool, depends_on=[f"S{n - 1}"] if n > 1 else [])
        for n, tool in enumerate(tools, start=1)
    ]
    plan.append(PlanStep(id=f"S{len(tools) + 1}", goal="write the answer with evidence", depends_on=[plan[-1].id]))
    triage = Triage(intent="other", entities=Entities(), urgency="normal", plan=plan)
    return ScriptedChatModel(script=[triage.model_dump_json()])


def run_variant_c(case: EvalCase, world: World, model: BaseChatModel | None = None) -> dict[str, Any]:
    kwargs = _tool_kwargs(case, world, case.steps)
    triage_model = None
    if model is None and world.offline:
        script = [tool_call_message(s.tool, s.args, call_id=f"c-{i}") for i, s in enumerate(case.steps, 1)]
        model = ScriptedChatModel(script=[*script, text_message(case.answer)])
        triage_model = _scripted_triage(case)
    agent = build_integrator(
        model or _online_model(),
        triage_model=triage_model or model or _online_model(),
        verifier=partial(verify_result, nli=world.nli, ledger_db=world.db_path),
        case_memory=world.case_memory(case, "C"),
        **kwargs,
    )
    return _outputs(investigate(agent, case.question, thread_id=f"eval-C-{case.id}"))


RUNNERS: dict[str, Callable[..., dict[str, Any]]] = {"A": run_variant_a, "B": run_variant_b, "C": run_variant_c}


